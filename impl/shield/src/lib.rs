/// The masking RNG for the hiding polynomial-commitment scheme.
///
/// All randomness is generated by `rand`'s [`ChaCha20Rng`] — the audited RustCrypto
/// ChaCha20 CSPRNG — so there is NO bespoke RNG algorithm in the proving path. The
/// only reason for this newtype is the hiding MMCS's `R: Rng + Clone + Send` bound
/// (`p3-merkle-tree`): upstream deliberately does not implement `Clone` on its
/// CSPRNGs (to discourage duplicating a keystream), so we add a faithful `Clone`
/// that reconstructs the generator's exact state from its public seed + stream +
/// word position via the crate's own accessors. Generation is 100% the vetted
/// implementation; only state reconstruction is ours (and is covered by a test).
struct MaskRng(ChaCha20Rng);

impl Clone for MaskRng {
    fn clone(&self) -> Self {
        let mut r = ChaCha20Rng::from_seed(self.0.get_seed());
        r.set_stream(self.0.get_stream());
        r.set_word_pos(self.0.get_word_pos());
        MaskRng(r)
    }
}
impl SeedableRng for MaskRng {
    type Seed = <ChaCha20Rng as SeedableRng>::Seed;
    fn from_seed(seed: Self::Seed) -> Self {
        MaskRng(ChaCha20Rng::from_seed(seed))
    }
}
impl TryRng for MaskRng {
    type Error = core::convert::Infallible;
    #[inline]
    fn try_next_u32(&mut self) -> Result<u32, Self::Error> {
        self.0.try_next_u32()
    }
    #[inline]
    fn try_next_u64(&mut self) -> Result<u64, Self::Error> {
        self.0.try_next_u64()
    }
    #[inline]
    fn try_fill_bytes(&mut self, dest: &mut [u8]) -> Result<(), Self::Error> {
        self.0.try_fill_bytes(dest)
    }
}

type Val = BabyBear;
// Degree-5 challenge extension (BabyBear^5 ≈ 2^154.6). A degree-4 extension
// (≈2^123.7) caps the DEEP/out-of-domain soundness terms below 128 bits; degree 5
// lifts that ceiling so the FRI query phase (below) is the only binding term.
type Challenge = BinomialExtensionField<Val, CHALLENGE_EXT_DEGREE>;
type ByteHash = Keccak256Hash;
type U64Hash = PaddingFreeSponge<KeccakF, 25, 17, 4>;
type FieldHash = SerializingHasher<U64Hash>;
type Compress = CompressionFunctionFromHasher<U64Hash, 2, 4>;
type ValHidingMmcs = MerkleTreeHidingMmcs<
    [Val; p3_keccak::VECTOR_LEN], [u64; p3_keccak::VECTOR_LEN],
    FieldHash, Compress, MaskRng, 2, 4, 4>;
type Challenger = SerializingChallenger32<Val, HashChallenger<u8, ByteHash, 32>>;
type ChallengeHidingMmcs = ExtensionMmcs<Val, Challenge, ValHidingMmcs>;
type Dft = Radix2DitParallel<Val>;
type HidingPcs = HidingFriPcs<Val, Dft, ValHidingMmcs, ChallengeHidingMmcs, MaskRng>;
type ZkConfig = StarkConfig<HidingPcs, Challenge, Challenger>;

/// A fresh CSPRNG seeded from operating-system entropy. The hiding PCS draws its
/// zero-knowledge masking randomness from these RNGs (random commitment columns +
/// quotient blinding); if that randomness is predictable, the "hiding" is void and
/// the witness (amounts, blinds, spend secrets) can be recovered from a proof — so
/// each proof MUST use fresh, unpredictable entropy from a cryptographic RNG.
fn os_rng() -> MaskRng {
    MaskRng::try_from_rng(&mut SysRng).expect("OS entropy unavailable for proof masking")
}

/// FRI query count. Fixed at the mainnet-grade value: there is deliberately NO
/// lower-security build variant (the former `high-security` cargo feature is gone), so
/// every binary (node, wallet, tools, tests) produces and verifies one proof format.
/// 112 queries · log_blowup 2. The Johnson bound is `(2−1)·112 + 20 = 132` bits,
/// and that is the figure the mainnet floor checks. The list-decoding conjecture
/// is `2·112 + 20 = 244` bits ([`conjectured_soundness_bits`]).
const FRI_NUM_QUERIES: usize = 112;

/// Proof-of-work grinding bits, applied on both the commit and the query phase.
const FRI_POW_BITS: usize = 20;

/// FRI code-rate exponent (blowup = 2^this). Shared by every config so the compiled
/// [`conjectured_soundness_bits`] below matches `fri_params.conjectured_soundness_bits()`.
const FRI_LOG_BLOWUP: usize = 2;

/// Mainnet FRI floor. The compiled constants above meet it by construction; the floor
/// is kept (and re-checked at node startup via [`assert_mainnet_grade`]) so a future
/// edit that lowers the constants can never ship silently.
pub const MAINNET_MIN_QUERIES: usize = 112;
pub const MAINNET_MIN_POW_BITS: usize = 20;
pub const MAINNET_MIN_SOUNDNESS_BITS: usize = 128;

/// The FRI query count baked into THIS binary.
pub const fn fri_num_queries() -> usize { FRI_NUM_QUERIES }
/// The FRI proof-of-work bits baked into THIS binary.
pub const fn fri_pow_bits() -> usize { FRI_POW_BITS }
/// Conjectured (list-decoding) FRI soundness bits of the compiled parameters:
/// `log_blowup·num_queries + query_pow`. Mirrors `FriParameters::conjectured_soundness_bits`
/// exactly (same formula, same inputs) so callers need not build a full config to read it.
pub const fn conjectured_soundness_bits() -> usize {
    FRI_LOG_BLOWUP * FRI_NUM_QUERIES + FRI_POW_BITS
}

/// Johnson-bound FRI soundness of the compiled rate. At blowup 4 the Johnson
/// radius gives about one bit per query: `(log_blowup − 1)·num_queries + query_pow`.
/// [`is_mainnet_grade`] and the config assert check this figure. It is the standard
/// estimate, not a tighter computation. [`conjectured_soundness_bits`] stays the
/// list-decoding conjecture.
pub const fn johnson_soundness_bits() -> usize {
    FRI_LOG_BLOWUP.saturating_sub(1) * FRI_NUM_QUERIES + FRI_POW_BITS
}

/// True iff the COMPILED FRI parameters meet the mainnet floor, measured against
/// the Johnson bound. Non-panicking twin of [`assert_mainnet_grade`]. Always
/// `true` for the shipped constants (132 ≥ 128).
pub fn is_mainnet_grade() -> bool {
    fri_num_queries() >= MAINNET_MIN_QUERIES
        && fri_pow_bits() >= MAINNET_MIN_POW_BITS
        && johnson_soundness_bits() >= MAINNET_MIN_SOUNDNESS_BITS
}

/// Panic unless this binary was compiled with mainnet-grade FRI parameters. Called once
/// at mainnet node startup (from the ABCI crate) so a binary whose FRI constants were
/// lowered refuses to run on mainnet rather than serve under-parameterised proofs.
pub fn assert_mainnet_grade() {
    assert!(
        is_mainnet_grade(),
        "shield proofs are BELOW mainnet grade: compiled FRI = {} queries / pow {} / {} \
         Johnson-bound bits ({} conjectured list-decoding bits); mainnet requires >= {} \
         queries, >= {} pow bits, >= {} soundness bits: the FRI constants in \
         zcrypt-shield were lowered; restore them",
        fri_num_queries(),
        fri_pow_bits(),
        johnson_soundness_bits(),
        conjectured_soundness_bits(),
        MAINNET_MIN_QUERIES,
        MAINNET_MIN_POW_BITS,
        MAINNET_MIN_SOUNDNESS_BITS,
    );
}

fn make_config(rng_input: MaskRng, rng_challenge: MaskRng, rng_pcs: MaskRng) -> ZkConfig {
    let byte_hash = ByteHash {};
    // Two independent MMCS instances (same hashing config, independent hiding RNGs)
    // so the input-commitment mask and the FRI-commitment mask never correlate.
    let mk_mmcs = |rng: MaskRng| {
        let u64_hash = U64Hash::new(KeccakF {});
        ValHidingMmcs::new(FieldHash::new(u64_hash), Compress::new(u64_hash), 0, rng)
    };
    let val_mmcs = mk_mmcs(rng_input);
    let challenge_mmcs = ChallengeHidingMmcs::new(mk_mmcs(rng_challenge));
    let dft = Dft::default();
    let fri_params = FriParameters {
        log_blowup: FRI_LOG_BLOWUP,
        log_final_poly_len: FRI_LOG_FINAL_POLY_LEN,
        max_log_arity: FRI_MAX_LOG_ARITY,
        num_queries: FRI_NUM_QUERIES,
        commit_proof_of_work_bits: FRI_POW_BITS,
        query_proof_of_work_bits: FRI_POW_BITS,
        mmcs: challenge_mmcs,
    };
    // Hard floor enforced in RELEASE builds too (was a debug_assert). The floor is
    // the Johnson bound, about one bit per query at this rate, not the list-decoding
    // conjecture. A binary under that floor must never build a proof.
    let johnson_bits = fri_params.num_queries * fri_params.log_blowup.saturating_sub(1)
        + fri_params.query_proof_of_work_bits;
    assert!(
        johnson_bits >= 100,
        "FRI parameters below the 100-bit Johnson-bound floor: {johnson_bits} bits",
    );
    let pcs = HidingPcs::new(dft, val_mmcs, fri_params, HIDING_QUOTIENT_RANDOM_COLS, rng_pcs);
    ZkConfig::new(pcs, Challenger::from_hasher(vec![], byte_hash))
}

/// Prover config: every hiding RNG is a fresh OS-seeded CSPRNG, so the ZK masking
/// is unpredictable and unique per proof.
fn prover_config() -> ZkConfig {
    make_config(os_rng(), os_rng(), os_rng())
}

/// Verifier config: verification never draws from these RNGs (they only mask the
/// prover's committed data), so a fixed seed here is safe and keeps verify
/// deterministic. The masking that mattered was already committed by the prover.
fn verifier_config() -> ZkConfig {
    make_config(
        MaskRng::seed_from_u64(0),
        MaskRng::seed_from_u64(0),
        MaskRng::seed_from_u64(0),
    )
}

const WIDTH: usize = 16;
const SD: u64 = 7;
const SR: usize = 1;
const HFR: usize = 4;
const PR: usize = 13;
const BLK: usize = num_cols::<WIDTH, SD, SR, HFR, PR>();
/// Range-check width of ONE value limb. A coin value is carried as two limbs
/// (`value = lo + hi·2^BITS`), each range-checked to `BITS` bits, so a coin holds
/// up to `2^(2·BITS) − 1`. `BITS = 26` (not more) keeps the conservation sums +
/// carry safely under the BabyBear field (~2^31) so the check can never wrap.
pub const BITS: usize = 26;
/// Limb boundary: `value = value_lo + value_hi · 2^SHIFT`.
pub const SHIFT: usize = BITS;
/// The largest value one coin can hold: `2^(2·BITS) − 1` ≈ 4.5×10¹⁵ base units.
/// (≈4.5 billion ZCRYPT at 1e6, or ≈45 million zBTC at 1e8 — no practical cap.)
pub const MAX_COIN_VALUE: u64 = (1u64 << (2 * BITS)) - 1;
pub const N_IN: usize = 2;
pub const N_OUT: usize = 2;
const S: usize = N_IN + N_OUT;
/// Commitment-tree depth the in-circuit Merkle path is proven against. MUST equal
/// [`tree::DEPTH`] so the circuit's recomputed root matches the node's tree root.
pub const DEPTH: usize = tree::DEPTH;
// Blocks per row: S commit blocks (inputs then outputs), N_IN nullifier blocks,
// N_IN spend-pubkey blocks (pk_i = Poseidon2(spend_secret_i), bound into the
// input commitment so ownership is enforced and the nullifier is canonical), then
// N_IN·DEPTH Merkle-path compression blocks (one Poseidon2 per tree level per
// input) that prove the spent coin is a real leaf under the public root.
// Inner hash blocks: the commitment and the nullifier are each TWO Poseidon2
// compressions (the 8-limb blind no longer fits beside pk/value/asset in one block).
// Inner commit i = [pk(8) ‖ blind(8)]; inner nullifier j = [spend_secret(8) ‖ blind(8)].
// Their 8-limb digests feed the outer (tagged) commit / nullifier blocks.
const INNER_C_BASE: usize = S + 2 * N_IN;
const INNER_NF_BASE: usize = INNER_C_BASE + S;
const PATH_BASE: usize = INNER_NF_BASE + N_IN;
const NBLK: usize = PATH_BASE + N_IN * DEPTH;
// Range-check columns: 2 limbs per coin, one limb for the fee, plus the carry.
const CARRY_BITS: usize = 4; // carry E, offset so E+8 ∈ [0,16) ⇒ E ∈ [-8,7]
const CARRY_OFFSET: u64 = 8;
const BITS_OFF: usize = NBLK * BLK;
const VAL_BITS: usize = S * 2 * BITS; // two limbs (lo,hi) per coin
const FEE_OFF: usize = BITS_OFF + VAL_BITS; // fee's BITS range bits
const CARRY_OFF: usize = FEE_OFF + BITS; // carry's CARRY_BITS bits
// Merkle path witness: per input, DEPTH sibling commitments (8 limbs each) and
// DEPTH direction bits (1 = the running node is the right child at that level).
const PATH_SIB_OFF: usize = CARRY_OFF + CARRY_BITS;
const PATH_DIR_OFF: usize = PATH_SIB_OFF + N_IN * DEPTH * 8;
// Per-input `active` flag: 1 = a real coin is spent here, 0 = canonical-null
// padding (value forced 0, nullifier forced to NULL_NF). Lets a spend use FEWER
// than N_IN real inputs (e.g. spend a single coin) without a fixed 2-input floor.
const ACT_OFF: usize = PATH_DIR_OFF + N_IN * DEPTH;
const W: usize = ACT_OFF + N_IN;
