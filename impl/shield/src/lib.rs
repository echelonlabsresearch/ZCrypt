/// BabyBear field modulus (`15·2^27 + 1`). A commitment / nullifier limb is a field
/// element, so a *canonical* on-chain encoding requires every limb to be `< P`.
/// Otherwise two distinct byte encodings (`x` and `x + P`) both reduce to the same
/// field element inside the proof — so the same proof verifies — yet hash to
/// different registry keys, which would let a spent nullifier re-enter the set: an
/// unlimited double-spend. Every deserialized commitment/nullifier MUST be checked.
pub const FIELD_ORDER: u64 = 2013265921; // 0x7800_0001

/// True iff every limb of `c` is a canonical field element (`< FIELD_ORDER`).
pub fn limbs_canonical(c: &Commitment) -> bool {
    c.iter().all(|&x| x < FIELD_ORDER)
}

/// Rejection-sample a uniform BabyBear limb from OS entropy.
pub fn rand_field_limb() -> u64 {
    // Rejection sampling: keep values in [0, floor(2^64/P)*P).
    const LIMIT: u64 = (u64::MAX / FIELD_ORDER) * FIELD_ORDER;
    let mut rng = SysRng;
    loop {
        let mut b = [0u8; 8];
        // SysRng implements TryRng in rand 0.10
        let _ = rng.try_fill_bytes(&mut b);
        let x = u64::from_le_bytes(b);
        if x < LIMIT {
            return x % FIELD_ORDER;
        }
    }
}

/// Reduce an arbitrary u64 into a canonical field limb (for deterministic KDFs).
#[inline]
pub fn field_limb(x: u64) -> u64 {
    x % FIELD_ORDER
}

/// The largest valid fee, one limb wide (`< 2^BITS`). A fee at or above this either
/// fails the circuit's range check or (via field reduction) desynchronizes the
/// node's raw-`u64` accounting from the proven value — reject it on the wire.
pub const MAX_FEE: u64 = 1u64 << BITS;

/// Number of field limbs in a blinding factor (~31 bits each): 8 limbs, about 248
/// bits, so a Grover search over the blind of a guessed amount is about 2^124.
pub const BLIND_LIMBS: usize = 8;
/// Canonical serialized size of a blind: 8 little-endian bytes per limb.
pub const BLIND_BYTES: usize = BLIND_LIMBS * 8;
// The inner commit / nullifier blocks absorb [8 lanes ‖ blind]; the blind must fill
// exactly the upper half of the permutation width.
const _: () = assert!(8 + BLIND_LIMBS == WIDTH, "blind must fill lanes 8..16 of the inner block");
/// Number of field limbs in a spend secret.
pub const SPEND_SECRET_LIMBS: usize = 8;

/// Blinding factor: 8 field elements (~248-bit hiding, ~124-bit against Grover).
/// Four limbs (~124-bit classical, ~62-bit quantum) was the previous width; eight
/// matches the ~252-bit blinds of Sapling/Orchard and keeps amount privacy at the
/// same post-quantum level as the spend secret.
pub type Blind = [u64; BLIND_LIMBS];
/// Spend secret: 8 field elements (~248-bit) so `pk = Poseidon2(spend_secret)`
/// cannot be inverted by brute force.
pub type SpendSecret = [u64; SPEND_SECRET_LIMBS];
/// Spend public key `= Poseidon2(spend_secret)`, bound into the coin commitment.
pub type PubKey = [u64; 8];

/// Fresh uniform blind (each limb rejection-sampled in the field).
pub fn random_blind() -> Blind {
    core::array::from_fn(|_| rand_field_limb())
}

/// Deterministically widen four limbs into a full 8-limb [`Blind`] (test / demo
/// convenience: fixtures written as four scalars keep working). Each extra limb is
/// the matching base limb plus a constant, reduced into the field.
pub fn widen_blind(limbs: [u64; 4]) -> Blind {
    core::array::from_fn(|i| field_limb(limbs[i % 4].wrapping_add((i / 4) as u64 * 0x9e37_79b9)))
}

/// Fresh uniform spend secret.
pub fn random_spend_secret() -> SpendSecret {
    core::array::from_fn(|_| rand_field_limb())
}

/// Number of public-input limbs the chain domain occupies. Each limb is a canonical
/// BabyBear element (about 30.9 bits), so five limbs bind about 154 bits of a
/// SHA3-256 digest of the chain id: a fork operator can no longer grind a colliding
/// chain id in 2^31 work (the old single FNV limb) and replay mainnet spends on it.
pub const CHAIN_DOMAIN_LIMBS: usize = 5;

/// Domain tag for a chain_id, as [`CHAIN_DOMAIN_LIMBS`] public field elements bound
/// into every proof: `SHA3-256("ZC-CHAIN" ‖ len(chain_id) ‖ chain_id)`, split into
/// little-endian u32 words and reduced into the field. Consensus constants, not
/// adversarial secrets, but the binding must be collision resistant across forks.
pub fn chain_domain(chain_id: &[u8]) -> [u64; CHAIN_DOMAIN_LIMBS] {
    use sha3::Digest;
    let mut hasher = sha3::Sha3_256::new();
    hasher.update(b"ZC-CHAIN");
    hasher.update((chain_id.len() as u64).to_le_bytes());
    hasher.update(chain_id);
    let d = hasher.finalize();
    core::array::from_fn(|i| {
        let w = u32::from_le_bytes([d[4 * i], d[4 * i + 1], d[4 * i + 2], d[4 * i + 3]]);
        field_limb(w as u64)
    })
}

/// Wallet-side spend witness: a coin `(value, blind, spend_secret)` plus the Merkle
/// authentication path proving it is a real leaf of the shielded pool. The
/// commitment binds `pk = Poseidon2(spend_secret)`, so only the holder of
/// `spend_secret` can spend, and the path proves the coin exists — together they
/// establish ownership of a genuine pool coin without revealing which leaf it is.
#[derive(Clone)]
pub struct SpendWitness {
    pub value: u64,
    pub blind: Blind,
    pub spend_secret: SpendSecret,
    /// Which shielded asset this coin holds (0 = native ZCRYPT). Bound into the
    /// commitment, so a coin of one asset can never be opened as another.
    pub asset_id: u64,
    /// Merkle authentication path of the real coin to the tree root: `DEPTH`
    /// sibling commitments bottom-up. Proven in-circuit so the spent coin is a real
    /// leaf (see `tree::path`). Empty is only valid for an inactive padding slot.
    pub path_siblings: Vec<Commitment>,
    /// Direction bits for the path: `true` = the running node is the right child at
    /// that level. Length `DEPTH`.
    pub path_dirs: Vec<bool>,
}

/// Output coin the sender creates: amount, blinding, the *recipient's* public key
/// (the sender knows `pk` but not the recipient's `spend_secret`, so it cannot
/// spend what it sends), and the asset id (0 = native ZCRYPT).
pub type OutCoin = (u64, Blind, PubKey, u64);

/// Native ZCRYPT asset id. All pre-asset coins are implicitly this (index 11 of
/// the commit preimage was zero padding), so existing commitments stay valid.
pub const ASSET_ZCRYPT: u64 = 0;

/// The sentinel nullifier an **inactive (padding) input** publishes. A real
/// nullifier is `Poseidon2(...)`, which is all-zero with probability ~2⁻²⁴⁸, so
/// the node safely treats a `NULL_NF` input as "no coin spent here": it does NOT
/// record it as a spend (so repeated pads never collide as a false double-spend).
pub const NULL_NF: Commitment = [0u64; 8];

fn eval_sbox<AB: AirBuilder<F = BabyBear>>(sbox: &SBox<AB::Var, SD, SR>, x: &mut AB::Expr, b: &mut AB) {
    let x3: AB::Expr = sbox.0[0].into();
    b.assert_eq(x3.clone(), x.cube());
    *x = x3.square() * x.clone();
}
fn eval_full<AB: AirBuilder<F = BabyBear>>(state: &mut [AB::Expr; WIDTH], fr: &FullRound<AB::Var, WIDTH, SD, SR>, rc: &[BabyBear; WIDTH], b: &mut AB) {
    for i in 0..WIDTH { state[i] += rc[i]; eval_sbox::<AB>(&fr.sbox[i], &mut state[i], b); }
    LL::external_linear_layer(state);
    for i in 0..WIDTH { b.assert_eq(state[i].clone(), fr.post[i]); state[i] = fr.post[i].into(); }
}
fn eval_partial<AB: AirBuilder<F = BabyBear>>(state: &mut [AB::Expr; WIDTH], pr: &PartialRound<AB::Var, WIDTH, SD, SR>, rc: &BabyBear, b: &mut AB) {
    state[0] += *rc; eval_sbox::<AB>(&pr.sbox, &mut state[0], b);
    b.assert_eq(state[0].clone(), pr.post_sbox); state[0] = pr.post_sbox.into();
    LL::internal_linear_layer(state);
}

/// Range-check `n` boolean columns at `off` and recompose them into a value.
fn recompose<AB: AirBuilder<F = BabyBear>>(builder: &mut AB, row: &[AB::Var], off: usize, n: usize) -> AB::Expr {
    let mut acc = AB::Expr::ZERO;
    let mut p = AB::Expr::ONE;
    for j in 0..n {
        let bit: AB::Expr = row[off + j].into();
        builder.assert_zero(bit.clone() * (bit.clone() - AB::Expr::ONE));
        acc += bit * p.clone();
        p = p.double();
    }
    acc
}
/// `2^k` as an AB::Expr (built by doubling to avoid field-constructor API churn).
fn pow2<AB: AirBuilder<F = BabyBear>>(k: usize) -> AB::Expr {
    let mut x = AB::Expr::ONE;
    for _ in 0..k {
        x = x.double();
    }
    x
}

struct CoinsAir;
impl BaseAir<BabyBear> for CoinsAir {
    fn width(&self) -> usize { W }
    fn num_public_values(&self) -> usize {
        // output commits + fee + nullifiers + Merkle-anchor root + chain domain + enc_digest.
        // The spent coins are NOT public — they are hidden leaves proven via the
        // in-circuit path. chain_domain binds the proof to a consensus chain_id; the trailing
        // 8-limb enc_notes digest binds the tx's encrypted notes (observed into the transcript,
        // not constrained) so they can't be stripped/replaced in the mempool.
        N_OUT * 8 + 1 + N_IN * 8 + 8 + CHAIN_DOMAIN_LIMBS + 8
    }
}

impl<AB: AirBuilder<F = BabyBear>> Air<AB> for CoinsAir {
    fn eval(&self, builder: &mut AB) {
        let main = builder.main();
        let row = main.current_slice();
        let pis: Vec<AB::Expr> = builder.public_values().iter().map(|x| (*x).into()).collect();
        let out_off = 0;
        let fee_i = N_OUT * 8;
        let nf_off = fee_i + 1;
        let root_off = nf_off + N_IN * 8; // public Merkle anchor root (8 limbs)
        let fee_pub = pis[fee_i].clone();

        // Run every Poseidon2 block. The digest is the feed-forward compression
        // Trunc_8(P(x) + x), the same function as `native_commit`.
        let mut outs: Vec<[AB::Expr; 8]> = Vec::with_capacity(NBLK);
        for d in 0..NBLK {
            let base = d * BLK;
            let cols: &Poseidon2Cols<AB::Var, WIDTH, SD, SR, HFR, PR> = row[base..base + BLK].borrow();
            let mut state: [AB::Expr; WIDTH] = core::array::from_fn(|k| cols.inputs[k].into());
            LL::external_linear_layer(&mut state);
            for r in 0..HFR { eval_full::<AB>(&mut state, &cols.beginning_full_rounds[r], &RC_EI[r], builder); }
            for r in 0..PR { eval_partial::<AB>(&mut state, &cols.partial_rounds[r], &RC_I[r], builder); }
            for r in 0..HFR { eval_full::<AB>(&mut state, &cols.ending_full_rounds[r], &RC_EF[r], builder); }
            outs.push(core::array::from_fn(|k| feed_forward::<AB>(cols.ending_full_rounds[HFR - 1].post[k], cols.inputs[k])));
        }

        // Layouts (WIDTH=16):
        //   inner commit  [0..8]=pk(8)  [8..16]=blind(8)                       (tagless)
        //   outer commit  [0]=value_lo [1]=value_hi [2..10]=inner_c(8) [10..14]=0 [14]=asset [15]=TAG_COMMIT
        //   inner nf      [0..8]=spend_secret(8)  [8..16]=blind(8)             (tagless)
        //   outer nf      [0..8]=inner_nf(8) [8]=value_lo [9]=value_hi [10..14]=0 [14]=asset [15]=TAG_NF
        //   pk            [0..8]=spend_secret(8), [8..15)=0, [15]=TAG_PK
        // Block indices: commit i -> i (0..S); nullifier j -> S+j; pk j -> S+N_IN+j;
        // inner commit i -> INNER_C_BASE+i; inner nullifier j -> INNER_NF_BASE+j.

        // SINGLE-ASSET: every coin (inputs + outputs) carries the same asset_id
        // (commit input[14]); with the per-asset conservation below you cannot turn
        // asset A into asset B.
        for i in 1..S {
            builder.assert_eq(row[i * BLK + 14], row[14]);
        }

        // per coin: range-check BOTH value limbs; inputs prove ownership + tree
        // membership, outputs are exposed.
        for i in 0..S {
            let lo = recompose::<AB>(builder, row, BITS_OFF + i * 2 * BITS, BITS);
            let hi = recompose::<AB>(builder, row, BITS_OFF + i * 2 * BITS + BITS, BITS);
            builder.assert_eq(lo, row[i * BLK].into()); // value_lo = commit input[0]
            builder.assert_eq(hi, row[i * BLK + 1].into()); // value_hi = commit input[1]
            // Outer commit lanes [2..10] carry the inner block's digest of (pk ‖ blind);
            // lanes [10..14] are zero, so the commitment has one canonical preimage layout.
            for t in 0..8 {
                builder.assert_eq(row[i * BLK + 2 + t], outs[INNER_C_BASE + i][t].clone());
            }
            for t in 10..14 {
                builder.assert_zero(row[i * BLK + t].into());
            }

            if i < N_IN {
                let pk_blk = S + N_IN + i; // pk_i = Poseidon2(spend_secret_i)
                let nf_blk = S + i;
                // ACTIVE flag: 1 = a real coin spent here, 0 = canonical-null padding.
                let act: AB::Expr = row[ACT_OFF + i].into();
                builder.assert_zero(act.clone() * (act.clone() - AB::Expr::ONE)); // boolean
                // Inactive ⇒ value forced to 0 (both limbs), so it contributes 0 to
                // conservation. Contrapositive: any non-zero value ⇒ act = 1 ⇒ the
                // ownership/membership/nullifier constraints below all bind — so value
                // can never be created by an unbacked "padding" input.
                let one_minus_act = AB::Expr::ONE - act.clone();
                builder.assert_zero(one_minus_act.clone() * Into::<AB::Expr>::into(row[i * BLK]));
                builder.assert_zero(one_minus_act * Into::<AB::Expr>::into(row[i * BLK + 1]));
                // Role tag: the input commitment's lane [15] is the commit tag, mirroring
                // the output-coin constraint below (kept in parity with the tall production
                // AIR). Real leaves are always built with lane[15]=TAG_COMMIT.
                builder.assert_eq(row[i * BLK + 15], konst::<AB>(TAG_COMMIT));
                let ic_blk = INNER_C_BASE + i;
                let inf_blk = INNER_NF_BASE + i;
                // OWNERSHIP: the pk absorbed by the inner commit block == Poseidon2(ss).
                // Kept unconditional (a pad still binds pk = Poseidon2(ss), trivially).
                // Together with the Merkle path below, this proves the prover knows the
                // spend secret of a genuine tree leaf `outs[i]` — no ring needed, the
                // spent coin hides among the ENTIRE pool.
                for t in 0..8 {
                    builder.assert_eq(row[ic_blk * BLK + t], outs[pk_blk][t].clone());
                }
                for t in 8..WIDTH - 1 {
                    builder.assert_zero(row[pk_blk * BLK + t].into());
                }
                builder.assert_eq(row[pk_blk * BLK + WIDTH - 1], konst::<AB>(TAG_PK));
                // CANONICAL nullifier, two blocks. Inner: [ss(8) ‖ blind(8)], the same
                // spend secret as the pk block and the same blind as the inner commit block.
                for t in 0..8 {
                    builder.assert_eq(row[inf_blk * BLK + t], row[pk_blk * BLK + t]);
                    builder.assert_eq(row[inf_blk * BLK + 8 + t], row[ic_blk * BLK + 8 + t]);
                }
                // Outer: [inner_nf(8), value_lo, value_hi, 0×4, asset, TAG_NF].
                for t in 0..8 {
                    builder.assert_eq(row[nf_blk * BLK + t], outs[inf_blk][t].clone());
                }
                builder.assert_eq(row[nf_blk * BLK + 8], row[i * BLK]);       // value_lo
                builder.assert_eq(row[nf_blk * BLK + 9], row[i * BLK + 1]);   // value_hi
                for t in 10..14 {
                    builder.assert_zero(row[nf_blk * BLK + t].into());
                }
                builder.assert_eq(row[nf_blk * BLK + 14], row[i * BLK + 14]); // asset_id
                builder.assert_eq(row[nf_blk * BLK + 15], konst::<AB>(TAG_NF));
                // MERKLE MEMBERSHIP: prove the spent coin commitment `outs[i]` is a
                // real leaf under the public anchor root, by recomputing the root
                // from an in-circuit authentication path. This is what lets a
                // verifier that sees ONLY the proof (a light client) trust the coin
                // exists — membership is no longer a trusted node-side check.
                //
                // Chain `cur` from the leaf up: at each level the running node and
                // its sibling are ordered by a boolean direction bit (a conditional
                // swap), then compressed with one Poseidon2 block. Gated by `act`:
                // an inactive padding input proves nothing (it spends no real coin).
                let mut cur: [AB::Expr; 8] = core::array::from_fn(|j| outs[i][j].clone());
                for lvl in 0..DEPTH {
                    let pblk = PATH_BASE + i * DEPTH + lvl;
                    let dir: AB::Expr = row[PATH_DIR_OFF + i * DEPTH + lvl].into();
                    builder.assert_zero(dir.clone() * (dir.clone() - AB::Expr::ONE)); // boolean
                    // Constrain this compression block's 16 input lanes to the
                    // conditional swap of (cur, sibling): dir=0 ⇒ [cur ‖ sib] (cur is
                    // the left child); dir=1 ⇒ [sib ‖ cur] (cur is the right child).
                    for j in 0..8 {
                        let sibj: AB::Expr = row[PATH_SIB_OFF + (i * DEPTH + lvl) * 8 + j].into();
                        let curj = cur[j].clone();
                        let left = curj.clone() + dir.clone() * (sibj.clone() - curj.clone());
                        let right = sibj.clone() + dir.clone() * (curj.clone() - sibj.clone());
                        builder.assert_eq(row[pblk * BLK + j], left);
                        builder.assert_eq(row[pblk * BLK + 8 + j], right);
                    }
                    cur = core::array::from_fn(|j| outs[pblk][j].clone());
                }
                // Active ⇒ the recomputed root equals the public anchor.
                for j in 0..8 {
                    builder.assert_zero(act.clone() * (cur[j].clone() - pis[root_off + j].clone()));
                }

                // Published nullifier = the computed Poseidon2 nullifier for EVERY
                // input, real or padding. A padding input has its value forced to 0
                // (above) and its Merkle membership left unproven (gated off by `act`),
                // but it still publishes a genuine nullifier of a value-0 DUMMY coin
                // under a fresh pseudo-random spend key. So a spend using FEWER than
                // N_IN real coins is indistinguishable on-chain from a full one — there
                // is no all-zero NULL_NF sentinel to give the input count away (the
                // arity-leak fix). The dummy nullifier is a Poseidon2 image of a hidden
                // key, so it is unique and unforgeable; recording it as spent blocks no
                // real coin (it corresponds to a value-0 phantom nobody else can name).
                let mut wf = builder.when_first_row();
                for k in 0..8 {
                    wf.assert_eq(outs[nf_blk][k].clone(), pis[nf_off + i * 8 + k].clone());
                }
            } else {
                // output coin: [14]=asset, [15] the commit role tag.
                builder.assert_eq(row[i * BLK + 15], konst::<AB>(TAG_COMMIT));
                let mut wf = builder.when_first_row();
                for j in 0..8 { wf.assert_eq(outs[i][j].clone(), pis[out_off + (i - N_IN) * 8 + j].clone()); }
            }
        }

        // FEE range-check (its own BITS bits) — bounds fee so conservation can't wrap.
        let fee_re = recompose::<AB>(builder, row, FEE_OFF, BITS);
        builder.assert_eq(fee_re, fee_pub.clone());

        // CONSERVATION (multi-limb with carry). value = value_lo + value_hi·2^SHIFT.
        //   D = Σin_lo − Σout_lo − fee     E = Σout_hi − Σin_hi  (the carry)
        //   require D == 2^SHIFT · E, with E range-checked small (via CARRY_OFF bits)
        //   so neither D, E, nor 2^SHIFT·E can wrap the field. That makes the field
        //   equality imply the true 2·BITS-bit integer equality Σin_value = Σout+fee.
        let lo = |i: usize| -> AB::Expr { row[i * BLK].into() };
        let hi = |i: usize| -> AB::Expr { row[i * BLK + 1].into() };
        let mut sum_in_lo = AB::Expr::ZERO;
        let mut sum_in_hi = AB::Expr::ZERO;
        for i in 0..N_IN {
            sum_in_lo += lo(i);
            sum_in_hi += hi(i);
        }
        let mut sum_out_lo = AB::Expr::ZERO;
        let mut sum_out_hi = AB::Expr::ZERO;
        for i in N_IN..S {
            sum_out_lo += lo(i);
            sum_out_hi += hi(i);
        }
        let d = sum_in_lo - sum_out_lo - fee_pub;
        let e = sum_out_hi - sum_in_hi;
        // range-check (E + CARRY_OFFSET) ∈ [0, 2^CARRY_BITS) ⇒ E ∈ [-8, 7]
        let e_shifted = recompose::<AB>(builder, row, CARRY_OFF, CARRY_BITS);
        builder.assert_eq(e_shifted, e.clone() + pow2::<AB>(3)); // CARRY_OFFSET = 8 = 2^3
        // D == 2^SHIFT · E
        builder.assert_zero(d - pow2::<AB>(SHIFT) * e);
    }
}

const LIMB_MASK: u64 = (1u64 << SHIFT) - 1;

/// Role tags pinned into lane 15 of every core Poseidon2 preimage, so the three hash
/// domains (coin commitment, nullifier, spend pubkey) can never coincide for any choice
/// of the other lanes. Before this, `pk_input(ss) == nf_input(ss, 0, [0; 4], 0)`, so a
/// zero-value zero-blind coin's nullifier equalled its owner's public key. The AIR
/// constrains lane 15 of each block to the matching tag (see `CoinsAir` / `CoinsAirTall`).
pub const TAG_COMMIT: u64 = 1;
pub const TAG_NF: u64 = 2;
pub const TAG_PK: u64 = 3;

/// A constant as an AIR expression.
fn konst<AB: AirBuilder<F = BabyBear>>(x: u64) -> AB::Expr {
    AB::Expr::from(BabyBear::from_u64(x))
}

// Inner commit block: [0..8]=pk(8) ‖ [8..16]=blind(8). Tagless: the role tag lives in
// the outer block, and a collision in an inner block is a Poseidon2 collision outright.
fn inner_coin_input(pk: &PubKey, blind: &Blind) -> [BabyBear; WIDTH] {
    let mut s = [BabyBear::ZERO; WIDTH];
    for i in 0..8 { s[i] = BabyBear::from_u64(pk[i]); }
    for i in 0..BLIND_LIMBS { s[8 + i] = BabyBear::from_u64(blind[i]); }
    s
}
// Outer commit block: [0]=vlo [1]=vhi [2..10]=inner(8) [10..14]=0 [14]=asset [15]=TAG_COMMIT
fn coin_input(value: u64, inner: &Commitment, asset_id: u64) -> [BabyBear; WIDTH] {
    // The asset lane is a field element: an id at or above the field order would alias
    // another id inside the circuit. Consensus rejects such ids on every wire; this guard
    // catches any caller that bypasses it in debug builds.
    debug_assert!(asset_id < FIELD_ORDER, "asset_id {asset_id} is not a canonical field element");
    let mut s = [BabyBear::ZERO; WIDTH];
    s[0] = BabyBear::from_u64(value & LIMB_MASK);
    s[1] = BabyBear::from_u64(value >> SHIFT);
    for i in 0..8 { s[2 + i] = BabyBear::from_u64(inner[i]); }
    s[14] = BabyBear::from_u64(asset_id);
    s[15] = BabyBear::from_u64(TAG_COMMIT);
    s
}
/// Both Poseidon2 blocks of a coin commitment: `(inner, outer)`, where
/// `commitment = native_commit(outer)` and `outer` absorbs `native_commit(inner)`.
fn coin_blocks(value: u64, blind: &Blind, pk: &PubKey, asset_id: u64) -> ([BabyBear; WIDTH], [BabyBear; WIDTH]) {
    let inner = inner_coin_input(pk, blind);
    let outer = coin_input(value, &native_commit(&inner), asset_id);
    (inner, outer)
}
// Pk: [0..8]=spend_secret, [8..15]=0, [15]=TAG_PK.
fn pk_input(spend_secret: &SpendSecret) -> [BabyBear; WIDTH] {
    let mut s = [BabyBear::ZERO; WIDTH];
    for i in 0..SPEND_SECRET_LIMBS { s[i] = BabyBear::from_u64(spend_secret[i]); }
    s[15] = BabyBear::from_u64(TAG_PK);
    s
}
// Inner nullifier block: [0..8]=spend_secret(8) ‖ [8..16]=blind(8). Tagless (see above).
fn inner_nf_input(spend_secret: &SpendSecret, blind: &Blind) -> [BabyBear; WIDTH] {
    let mut s = [BabyBear::ZERO; WIDTH];
    for i in 0..SPEND_SECRET_LIMBS { s[i] = BabyBear::from_u64(spend_secret[i]); }
    for i in 0..BLIND_LIMBS { s[8 + i] = BabyBear::from_u64(blind[i]); }
    s
}
// Outer nullifier block: [0..8]=inner_nf [8]=vlo [9]=vhi [10..14]=0 [14]=asset [15]=TAG_NF
fn nf_input(inner: &Commitment, value: u64, asset_id: u64) -> [BabyBear; WIDTH] {
    debug_assert!(asset_id < FIELD_ORDER, "asset_id {asset_id} is not a canonical field element");
    let mut s = [BabyBear::ZERO; WIDTH];
    for i in 0..8 { s[i] = BabyBear::from_u64(inner[i]); }
    s[8] = BabyBear::from_u64(value & LIMB_MASK);
    s[9] = BabyBear::from_u64(value >> SHIFT);
    s[14] = BabyBear::from_u64(asset_id);
    s[15] = BabyBear::from_u64(TAG_NF);
    s
}
/// Both Poseidon2 blocks of a nullifier: `(inner, outer)`; `nf = native_commit(outer)`.
fn nf_blocks(spend_secret: &SpendSecret, value: u64, blind: &Blind, asset_id: u64) -> ([BabyBear; WIDTH], [BabyBear; WIDTH]) {
    let inner = inner_nf_input(spend_secret, blind);
    let outer = nf_input(&native_commit(&inner), value, asset_id);
    (inner, outer)
}
/// Feed-forward digest lane: `P(x)[k] + x[k]`, field addition. Shared by every AIR
/// so the circuit and [`native_commit`] name the same compression.
fn feed_forward<AB: AirBuilder<F = BabyBear>>(post: AB::Var, input: AB::Var) -> AB::Expr {
    let permuted: AB::Expr = post.into();
    let preimage: AB::Expr = input.into();
    permuted + preimage
}

/// Poseidon2 compression: one width-16 permutation, then `Trunc_8(P(x) + x)`.
fn native_commit(input: &[BabyBear; WIDTH]) -> Commitment {
    let perm = default_babybear_poseidon2_16();
    let mut out = *input;
    perm.permute_mut(&mut out);
    core::array::from_fn(|i| (out[i] + input[i]).as_canonical_u64())
}

/// The spend public key, the compression of the spend secret. Publishing it
/// (in an address / coin commitment) does not reveal the spending secret.
pub fn spend_pubkey(spend_secret: &SpendSecret) -> PubKey { native_commit(&pk_input(spend_secret)) }
/// Coin commitment for native ZCRYPT.
pub fn commit(value: u64, blind: &Blind, pk: &PubKey) -> Commitment {
    commit_asset(value, blind, pk, ASSET_ZCRYPT)
}
/// Coin commitment for a shielded asset. Binds amount, owner, and asset, so a
/// coin of one asset cannot be opened as another.
pub fn commit_asset(value: u64, blind: &Blind, pk: &PubKey, asset_id: u64) -> Commitment {
    native_commit(&coin_blocks(value, blind, pk, asset_id).1)
}
/// Canonical nullifier for native ZCRYPT.
pub fn nullifier(spend_secret: &SpendSecret, value: u64, blind: &Blind) -> Commitment {
    nullifier_asset(spend_secret, value, blind, ASSET_ZCRYPT)
}
/// Canonical nullifier for a shielded-asset coin.
pub fn nullifier_asset(spend_secret: &SpendSecret, value: u64, blind: &Blind, asset_id: u64) -> Commitment {
    native_commit(&nf_blocks(spend_secret, value, blind, asset_id).1)
}

/// Domain tag for [`secret_coin_tag`]. The nullifier pins lane 15 to [`TAG_NF`];
/// the secret tag overwrites that lane, so the two compressions differ and neither
/// digest is computable from the other.
const COIN_TAG_DOMAIN: u64 = 0x00_C0_1A_67;

/// A **secret** per-coin tag: the same binding tuple as the nullifier
/// (`spend_secret, value, blind, asset`) hashed under a separate domain. Unlike the
/// nullifier it is never published, so it can key derivations that must stay hidden
/// from chain observers (see [`dummy_witness`]) while inheriting the nullifier's
/// per-coin uniqueness. Recovering it needs the coin's spend secret and blind, so it
/// is not computable from anything the chain reveals.
fn secret_coin_tag(spend_secret: &SpendSecret, value: u64, blind: &Blind, asset_id: u64) -> Commitment {
    let (_, mut s) = nf_blocks(spend_secret, value, blind, asset_id);
    s[WIDTH - 1] = BabyBear::from_u64(COIN_TAG_DOMAIN);
    native_commit(&s)
}
pub fn compress2(l: &Commitment, r: &Commitment) -> Commitment {
    let mut input = [BabyBear::ZERO; WIDTH];
    for i in 0..8 { input[i] = BabyBear::from_u64(l[i]); input[8 + i] = BabyBear::from_u64(r[i]); }
    native_commit(&input)
}

